using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace PinguApps.BlazorContentContracts.Analyzers;

[Generator]
public sealed class CompiledContentGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var enabled = context.AnalyzerConfigOptionsProvider.Select((options, _) =>
            !options.GlobalOptions.TryGetValue("build_property.BlazorContentContractsPublishSummaries", out var value)
            || !string.Equals(value, "false", StringComparison.OrdinalIgnoreCase));
        context.RegisterSourceOutput(context.CompilationProvider.Combine(context.AdditionalTextsProvider.Collect()).Combine(enabled),
            (production, input) =>
            {
                if (input.Right)
                {
                    Execute(production, input.Left.Left, input.Left.Right);
                }
            });
    }

    private static void Execute(SourceProductionContext context, Compilation compilation, System.Collections.Immutable.ImmutableArray<AdditionalText> files)
    {
        if (compilation.GetTypeByMetadataName("PinguApps.BlazorContentContracts.CompiledContentAttribute") == null
            || !CompiledMetadataAnalyzer.Compatible(compilation))
        {
            return;
        }

        var options = compilation.SyntaxTrees.FirstOrDefault()?.Options as CSharpParseOptions;
        var razorPaths = new HashSet<string>(files.Where(file => file.Path.EndsWith(".razor", StringComparison.OrdinalIgnoreCase))
            .Select(file => file.Path), StringComparer.Ordinal);
        var razor = files.Where(file => file.Path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase))
            .Select(file => (file.Path, Text: file.GetText(context.CancellationToken)))
            .Where(file => file.Text != null && file.Text.ToString().Contains("#pragma checksum"))
            .Select(file => CSharpSyntaxTree.ParseText(file.Text!, options, file.Path, cancellationToken: context.CancellationToken))
            .Where(tree => tree.GetRoot(context.CancellationToken).GetLeadingTrivia().Select(trivia => trivia.GetStructure())
                .OfType<PragmaChecksumDirectiveTriviaSyntax>().Any(checksum => razorPaths.Contains(checksum.File.ValueText))).ToArray();
        compilation = compilation.AddSyntaxTrees(razor);
        var output = new StringBuilder("// <auto-generated/>\n");

        foreach (var tree in compilation.SyntaxTrees)
        {
            var model = compilation.GetSemanticModel(tree);

            foreach (var method in tree.GetRoot(context.CancellationToken).DescendantNodes().OfType<MethodDeclarationSyntax>()
                .Where(method => method.Identifier.ValueText == "BuildRenderTree"))
            {
                context.CancellationToken.ThrowIfCancellationRequested();

                if (model.GetDeclaredSymbol(method, context.CancellationToken) is not IMethodSymbol { IsOverride: true } symbol
                    || symbol.ContainingType.ContainingType != null
                    || symbol.ContainingType.IsFileLocal
                    || !symbol.ContainingType.AllInterfaces.Any(type => type.ToDisplayString() == "Microsoft.AspNetCore.Components.IComponent")
                    || OutputContractAnalyzer.OutputContract(symbol.ContainingType, compilation) != null
                    || method.Body == null)
                {
                    continue;
                }

                var types = new HashSet<string>();
                var elements = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
                var forwards = new HashSet<string>();
                var text = false;
                var supported = true;
                var depth = 0;
                var frames = new Stack<BlockSyntax>();

                foreach (var call in method.Body.DescendantNodes().OfType<InvocationExpressionSyntax>())
                {
                    if (call.Ancestors().TakeWhile(node => node != method.Body).Any(node => node is LambdaExpressionSyntax or LocalFunctionStatementSyntax))
                    {
                        continue;
                    }

                    var invoked = model.GetSymbolInfo(call, context.CancellationToken).Symbol as IMethodSymbol;

                    if (invoked?.ContainingType.ToDisplayString() != "Microsoft.AspNetCore.Components.Rendering.RenderTreeBuilder")
                    {
                        if (invoked?.MethodKind == MethodKind.DelegateInvoke
                            && model.GetSymbolInfo(call.Expression, context.CancellationToken).Symbol is IPropertySymbol template
                            && ContentContractAnalyzer.IsFragment(template.Type)
                            && forwards.Contains(template.Name))
                        {
                            continue;
                        }

                        supported = false;
                        break;
                    }

                    if (invoked.Name == "OpenComponent")
                    {
                        if (call.Parent is not ExpressionStatementSyntax { Parent: BlockSyntax block })
                        {
                            supported = false;
                            break;
                        }

                        frames.Push(block);

                        if (depth++ == 0)
                        {
                            var component = invoked.TypeArguments.FirstOrDefault() as INamedTypeSymbol;

                            if (component == null || ContainsTypeParameter(component)
                                || !compilation.IsSymbolAccessibleWithin(component, compilation.Assembly))
                            {
                                supported = false;
                                break;
                            }

                            types.Add(component.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                        }

                        continue;
                    }

                    if (invoked.Name == "CloseComponent")
                    {
                        if (frames.Count == 0 || call.Parent is not ExpressionStatementSyntax { Parent: BlockSyntax block }
                            || frames.Pop() != block)
                        {
                            supported = false;
                            break;
                        }

                        depth--;
                        continue;
                    }

                    if (depth > 0)
                    {
                        continue;
                    }

                    if (invoked.Name is "CloseElement" or "OpenRegion" or "CloseRegion" or "AddAttribute" or "SetKey")
                    {
                        continue;
                    }

                    if (call.ArgumentList.Arguments.Count < 2)
                    {
                        supported = false;
                        break;
                    }

                    var value = call.ArgumentList.Arguments[1].Expression;
                    var constant = model.GetConstantValue(value, context.CancellationToken);

                    if (invoked.Name == "OpenElement" && constant.Value is string element)
                    {
                        elements.Add(element);
                    }
                    else if (invoked.Name is "AddContent" or "AddMarkupContent" && constant.HasValue)
                    {
                        if (!string.IsNullOrWhiteSpace(constant.Value?.ToString()))
                        {
                            if (invoked.Name == "AddMarkupContent")
                            {
                                supported = false;
                                break;
                            }

                            text = true;
                        }
                    }
                    else if (invoked.Name == "AddContent" && model.GetSymbolInfo(value is InvocationExpressionSyntax invocation ? invocation.Expression : value, context.CancellationToken).Symbol is IPropertySymbol property
                        && property.ContainingType.Equals(symbol.ContainingType, SymbolEqualityComparer.Default)
                        && ContentContractAnalyzer.IsFragment(property.Type)
                        && property.GetAttributes().Any(attribute => attribute.AttributeClass?.ToDisplayString() == "Microsoft.AspNetCore.Components.ParameterAttribute")
                        && SafeParameter(property, compilation, context.CancellationToken))
                    {
                        forwards.Add(property.Name);
                    }
                    else
                    {
                        supported = false;
                        break;
                    }
                }

                if (!supported || depth != 0 || method.Body.DescendantNodes().Any(node => node is ThrowStatementSyntax
                    or AwaitExpressionSyntax or AssignmentExpressionSyntax or ObjectCreationExpressionSyntax or ImplicitObjectCreationExpressionSyntax))
                {
                    continue;
                }

                var target = symbol.ContainingType.IsGenericType ? symbol.ContainingType.ConstructUnboundGenericType() : symbol.ContainingType;
                var targetName = target.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                output.Append("[assembly: global::PinguApps.BlazorContentContracts.CompiledContent(new global::System.Type[] { ")
                    .Append(string.Join(", ", types.OrderBy(value => value).Select(value => "typeof(" + value + ")")))
                    .Append(" }, typeof(").Append(targetName).Append("), Version = 1, HtmlElements = new string[] { ")
                    .Append(string.Join(", ", elements.OrderBy(value => value).Select(value => SymbolDisplay.FormatLiteral(value, true))))
                    .Append(" }, AllowText = ").Append(text ? "true" : "false").Append(")]\n");

                if (forwards.Count > 0)
                {
                    output.Append("[assembly: global::PinguApps.BlazorContentContracts.CompiledForwarding(new string[] { ")
                        .Append(string.Join(", ", forwards.OrderBy(value => value).Select(value => SymbolDisplay.FormatLiteral(value, true))))
                        .Append(" }, typeof(").Append(targetName).Append("), Version = 1)]\n");
                }
            }
        }

        context.AddSource("CompiledContent.g.cs", SourceText.From(output.ToString(), Encoding.UTF8));
    }

    private static bool ContainsTypeParameter(ITypeSymbol type)
    {
        return type.TypeKind == TypeKind.TypeParameter
            || type is INamedTypeSymbol named && (named.TypeArguments.Any(ContainsTypeParameter)
                || named.ContainingType != null && ContainsTypeParameter(named.ContainingType))
            || type is IArrayTypeSymbol array && ContainsTypeParameter(array.ElementType);
    }

    private static bool SafeParameter(IPropertySymbol property, Compilation compilation, System.Threading.CancellationToken cancellationToken)
    {
        if (property.DeclaringSyntaxReferences.Any(reference => reference.GetSyntax(cancellationToken) is not PropertyDeclarationSyntax declaration
            || declaration.Initializer != null || declaration.ExpressionBody != null
            || declaration.AccessorList == null || declaration.AccessorList.Accessors.Any(accessor => accessor.Body != null || accessor.ExpressionBody != null)))
        {
            return false;
        }

        foreach (var reference in property.ContainingType.DeclaringSyntaxReferences)
        {
            var declaration = reference.GetSyntax(cancellationToken);
            var model = compilation.GetSemanticModel(declaration.SyntaxTree);

            if (declaration.DescendantNodes().OfType<AssignmentExpressionSyntax>().Any(assignment =>
                SymbolEqualityComparer.Default.Equals(model.GetSymbolInfo(assignment.Left, cancellationToken).Symbol, property)))
            {
                return false;
            }
        }

        return true;
    }
}
